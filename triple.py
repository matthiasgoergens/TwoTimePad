  def make_model(n):
    inputA = Input(shape=(n,), dtype='int32', name="cipherA")
    inputB = Input(shape=(n,), dtype='int32', name="cipherB")
    inputKeys = Input(shape=(n,), dtype='int32', name="keysCorrupted")

    emb = Embedding(output_dim=len(alpha), input_dim=len(alpha), name="my_embedding")
    embKeys = Embedding(output_dim=len(alpha), input_dim=len(alpha)+1, name="my_embeddingKeys")
    embeddedA = emb(inputA)
    embeddedB = emb(inputB)
    embeddedKeys = embKeys(inputKeys)
    embedded = Concatenate()([embeddedA, embeddedB, embeddedKeys])

    # relud = lambda base: relu()(Dense()(base))
    # Idea is to bubble up better and better guesses for what letters we have locally.
    conv1 = lambda base: BatchNormalization()(Conv1D(
        filters=46*2*2 * 5, kernel_size=5,
        padding='same', strides=1)(
          base
        ))

    conv = lambda base: Add()([base, conv1(Maxout(46*2*2)(base))])
    # Not sure whether the eta abstraction is necessary?
    lstm_ed = (
      (conv(
      (conv(
      (conv(
      (conv(
      (conv(
      (conv(
      (conv(
      (conv(
      conv1(embedded)
    )))))))))))))))))

    totes_clear = (
      Softmax(name="clear")(Conv1D(
        filters=len(alpha), kernel_size=5,
        padding='same', strides=1)(
      lstm_ed
    )))
    totes_key = (
      Softmax(name="key")(Conv1D(
        filters=len(alpha), kernel_size=5,
        padding='same', strides=1)(
      lstm_ed
    )))
    #totes_cipher = (
    #  Softmax(name="cipher_again")(Conv1D(
    #    filters=len(alpha), kernel_size=1,
    #    padding='same', strides=1)(
    #  relu()(Conv1D(
    #    filters=len(alpha)*2, kernel_size=1,
    #    padding='same', strides=1)(
    #  relu()(Conv1D(
    #    filters=len(alpha)*2, kernel_size=1,
    #    padding='same', strides=1)(
    #  relu()(Conv1D(
    #    filters=len(alpha)*2, kernel_size=1,
    #    padding='same', strides=1)(
    #  concatenate([totes_key, totes_clear])
    #)))))))))
    model = Model([inputA, inputB, inputKeys], [totes_clear, totes_key])

    model.compile(
      optimizer='adam',
      loss='sparse_categorical_crossentropy',
      metrics=['accuracy'])
    return model

