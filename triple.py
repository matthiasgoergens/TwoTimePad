  alpha =    " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.?,-:;'()".lower()
  alphaRE = alpha.replace("-","\\-")

  assert len(alpha) == 46

  def load():
    text = ' '.join(f.open('r').read() for f in pathlib.Path('data').glob('*.txt')).lower()
    text = re.sub('\s+', ' ', text)
    text = re.sub(f'[^{alphaRE}]', '', text)
    return text

  def add(clear, key):
    return [(a+b) % len(alpha) for a, b in zip(clear, key)]

  def sub(cipher, key):
    return [(a-b) % len(alpha) for a, b in zip(cipher, key)]

  def clean(text):
    t = {c: i for i, c in enumerate(alpha)}
    return [t[c] for c in text]

  def toChar(numbers):
    return ''.join(alpha[i] for i in numbers)

  # toChar
  # (5, 125, 46)
  def toChars(tensor):
    (linesNums, charNum, alphaNum) = tensor.shape
    output = []
    # TODO: use gather https://www.tensorflow.org/api_docs/python/tf/gather?version=stable
    assert alphaNum == len(alpha)
    for lineNum in range(linesNums):
      chars = []
      for cN in range(charNum):
        (_, char) = max([(tensor[lineNum, cN, alphaN], alphaN) for alphaN in range(alphaNum)])
        chars.append(char)
      output.append(toChar(chars))
    return output

  def toChars_labels(labels):
    (linesNums, charNum) = labels.shape
    output = []
    for lineNum in range(linesNums):
      chars = []
      for cN in range(charNum):
        chars.append(labels[lineNum, cN])
      output.append(toChar(chars))
    return output


  def prepare(clear, key):
    assert len(clear) == len(key), (clear, key)

    # depth = len(alpha)

    # label = clear[len(clear)//2:len(clear)//2+1]
    return sub(clear, key)



  def sample(text, l):
    start = random.randrange(len(text) - l)
    return text[start:start+l]

  def samples(text, batch_size, l, drop_rate = 0.0):
    ciphersA = []
    ciphersB = []
    keys = []
    labelsA = []
    labelsB = []
    for _ in range(batch_size):
      clearA = sample(text, l)
      clearB = sample(text, l)
      key = [random.randrange(46) for _ in range(l)]

      cipherA = prepare(clearA, key)
      cipherB = prepare(clearB, key)
      # print(toChar(clear))
      # print(toChar(key))
      # print(toChar(add(clear, key)))
      # print(toChar(sub(add(clear, key), key)))
      ciphersA.append(cipherA)
      ciphersB.append(cipherB)
      labelsA.append(clearA)
      labelsB.append(clearB)

      key_corrupted_raw = [((random.random() >= drop_rate) * (k+1)) for k in key]
      key_corrupted = tf.convert_to_tensor(key_corrupted_raw) # Zero means corrupted..

      keys.append(key_corrupted)

    one_hot_ciphersA = tf.convert_to_tensor(ciphersA)
    one_hot_ciphersB = tf.convert_to_tensor(ciphersB)
    keys = tf.convert_to_tensor(keys)
    
    # print(one_hot_ciphers.shape)
    # print(one_hot_labels.shape)
    # print(len(one_hot_labels))
    return ([one_hot_ciphersA, one_hot_ciphersB, keys],
          [ tf.convert_to_tensor(labelsA),  tf.convert_to_tensor(labelsB)])

  # relu = keras.activations.relu # (alpha=0.1)
  relu = lambda: keras.layers.LeakyReLU(alpha=0.1)
  # keras.layers.Embedding

  from tensorflow.keras.layers import BatchNormalization, Concatenate, Embedding, Input, Dense, Dropout, Softmax, GlobalMaxPooling1D, MaxPooling1D, Conv1D, Flatten, concatenate, Bidirectional, LSTM, SimpleRNN, Add
  from tensorflow.keras.models import Sequential, Model
